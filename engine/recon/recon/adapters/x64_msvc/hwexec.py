"""Run one synthetic x86-64 instruction on this machine's processor and read the whole integer state back.

Used only to validate the lifter. The code executed is generated by `validate.py`, one instruction at a time
between a fixed prologue and epilogue; nothing of a target image is ever executed. The register file, the
flags and the stack pointer come from a state block, memory operands point into a scratch window.
"""
from __future__ import annotations

import ctypes
import mmap
import struct
import sys

from recon.adapters.x64_msvc.lift import GPR

REGION = 0x20000
STATE = 0x8000          # offsets inside the region
MEM = 0x10000           # scratch window for memory operands
MEM_SIZE = 0x2000
STACK = 0x14000
STACK_SIZE = 0x8000
TEST = 0x400            # where the instruction under test sits
TAKEN = TEST + 0x40     # where a taken branch lands (within reach of an 8-bit displacement)
STORE = TEST + 0x80

# state block, in qwords
IN_REGS, IN_FLAGS, OUT_REGS, OUT_FLAGS, HOST_SP, MARK = 0, 16, 17, 33, 34, 35

FLAG_BITS = {"cf": 0, "pf": 2, "af": 4, "zf": 6, "sf": 7, "df": 10, "of": 11}
FLAG_MASK = sum(1 << b for b in FLAG_BITS.values())
FLAG_FIXED = 0x202  # interrupt flag and the reserved bit


class Processor:
    """An executable region with the harness around one instruction slot."""

    def __init__(self, at: int | None = None) -> None:
        """With `at`, the region sits at that address (to repeat a vector whose operands are absolute) or RuntimeError."""
        if sys.maxsize < 2**32 or sys.byteorder != "little":
            raise RuntimeError("needs a 64-bit little-endian host")
        self._win = sys.platform == "win32"
        if self._win:
            k = ctypes.WinDLL("kernel32", use_last_error=True)
            k.VirtualAlloc.restype = ctypes.c_void_p
            k.VirtualAlloc.argtypes = (ctypes.c_void_p, ctypes.c_size_t, ctypes.c_uint32, ctypes.c_uint32)
            self.base = k.VirtualAlloc(at, REGION, 0x3000, 0x40)
            if not self.base:
                raise RuntimeError("could not allocate executable memory")
        else:
            c = ctypes.CDLL(None, use_errno=True)
            c.mmap.restype = ctypes.c_void_p
            c.mmap.argtypes = (ctypes.c_void_p, ctypes.c_size_t, ctypes.c_int, ctypes.c_int, ctypes.c_int, ctypes.c_long)
            rwx = mmap.PROT_READ | mmap.PROT_WRITE | mmap.PROT_EXEC
            self.base = c.mmap(at, REGION, rwx, mmap.MAP_PRIVATE | mmap.MAP_ANONYMOUS, -1, 0)
            if self.base in (None, 2**64 - 1):
                raise RuntimeError("could not allocate executable memory")
        if at is not None and self.base != at:
            raise RuntimeError("the region could not be placed at the wanted address")
        self.state = (ctypes.c_uint64 * 64).from_address(self.base + STATE)
        self._call = ctypes.CFUNCTYPE(None)(self.base)
        self._build()

    # -- addresses the generator needs ----------------------------------------------------------
    @property
    def test_ip(self) -> int:
        return self.base + TEST

    @property
    def taken_ip(self) -> int:
        return self.base + TAKEN

    @property
    def mem(self) -> int:
        return self.base + MEM

    @property
    def stack(self) -> int:
        return self.base + STACK

    # -- building -------------------------------------------------------------------------------
    def _poke(self, off: int, data: bytes) -> None:
        ctypes.memmove(self.base + off, data, len(data))

    def _rip(self, at: int, head: bytes, qword: int, tail: bytes = b"") -> bytes:
        """`head` then a rip-relative displacement to a state qword, then `tail` (an immediate)."""
        end = at + len(head) + 4 + len(tail)
        return head + struct.pack("<i", STATE + 8 * qword - end) + tail

    def _mov(self, at: int, reg: int, qword: int, load: bool) -> bytes:
        rex = 0x48 | (4 if reg >= 8 else 0)
        return self._rip(at, bytes([rex, 0x8B if load else 0x89, 0x05 | (reg & 7) << 3]), qword)

    def _build(self) -> None:
        sp = GPR.index("rsp")
        code = bytes([0x53, 0x55, 0x57, 0x56, 0x41, 0x54, 0x41, 0x55, 0x41, 0x56, 0x41, 0x57])  # the host's saved registers
        code += self._mov(len(code), sp, HOST_SP, load=False)
        code += self._rip(len(code), b"\xFF\x35", IN_FLAGS) + b"\x9D"  # push [flags] ; popfq
        for r in range(16):  # mov does not touch flags
            code += self._mov(len(code), r, IN_REGS + r, load=True)
        code += b"\xE9" + struct.pack("<i", TEST - (len(code) + 5))
        assert len(code) < TEST
        self._poke(0, code)
        t = self._rip(TAKEN, b"\xC7\x05", MARK, struct.pack("<I", 1))
        t += b"\xE9" + struct.pack("<i", STORE - (TAKEN + len(t) + 5))
        self._poke(TAKEN, t)
        s = b""
        for r in range(16):
            s += self._mov(STORE + len(s), r, OUT_REGS + r, load=False)
        s += self._mov(STORE + len(s), sp, HOST_SP, load=True)
        s += b"\x9C" + self._rip(STORE + len(s) + 1, b"\x8F\x05", OUT_FLAGS) + b"\xFC"  # pushfq ; pop [out] ; cld
        s += bytes([0x41, 0x5F, 0x41, 0x5E, 0x41, 0x5D, 0x41, 0x5C, 0x5E, 0x5F, 0x5D, 0x5B, 0xC3])
        self._poke(STORE, s)

    def load(self, insn: bytes) -> None:
        """Place the instruction under test; a fall-through marks 0 and continues at the state store."""
        at = TEST + len(insn)
        tail = self._rip(at, b"\xC7\x05", MARK, struct.pack("<I", 0))
        tail += b"\xE9" + struct.pack("<i", STORE - (at + len(tail) + 5))
        assert at + len(tail) <= TAKEN
        self._poke(TEST, insn + tail)

    # -- running --------------------------------------------------------------------------------
    def run(self, regs: dict[str, int], flags: dict[str, int], windows: list[tuple[int, bytes]]) -> tuple[dict[str, int], dict[str, int], int, list[bytes]]:
        """(registers, flags, 1 when control left through the taken label, the windows' bytes afterwards)."""
        st = self.state
        for k, n in enumerate(GPR):
            st[IN_REGS + k] = regs[n]
        st[IN_FLAGS] = FLAG_FIXED | sum(flags[n] << b for n, b in FLAG_BITS.items())
        st[MARK] = 2
        for addr, data in windows:
            ctypes.memmove(addr, data, len(data))
        self._call()
        fl = st[OUT_FLAGS]
        out_windows = [ctypes.string_at(addr, len(data)) for addr, data in windows]
        return ({n: st[OUT_REGS + k] for k, n in enumerate(GPR)}, {n: fl >> b & 1 for n, b in FLAG_BITS.items()}, st[MARK], out_windows)
